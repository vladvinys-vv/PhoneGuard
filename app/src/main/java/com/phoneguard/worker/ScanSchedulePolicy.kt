package com.phoneguard.worker

/**
 * Согласованность настройки «периодическое сканирование» и фактической работы.
 *
 * Настройка — обещание пользователю. Она расходилась с поведением в двух местах:
 *
 *  * `ScheduledFullScanWorker` запускался по расписанию и **не проверял настройку**. Работа,
 *    поставленная до выключения (или восстановленная планировщиком, или оставшаяся от прошлой
 *    версии), выполняла полное сканирование устройства уже после того, как пользователь
 *    выключил периодичность — то есть тяжёлая проверка шла вопреки явному выбору;
 *  * включение настройки сразу сохранялось в DataStore, и только потом ставилась работа. Если
 *    планировщик отказывал (лимит работ, отключённый WorkManager у некоторых прошивок),
 *    интерфейс показывал «включено», а сканирование не приходило никогда.
 *
 * Правила здесь чистые, чтобы обе ветки ловились тестом.
 */
internal object ScanSchedulePolicy {

    /** Что делать воркеру, когда он всё-таки запустился. */
    enum class Verdict {
        /** Сканировать. */
        RUN,

        /** Настройка выключена — работу надо тихо завершить, а не повторять. */
        SKIP_SETTING_DISABLED
    }

    fun verdict(scheduledScanEnabled: Boolean): Verdict =
        if (scheduledScanEnabled) Verdict.RUN else Verdict.SKIP_SETTING_DISABLED

    /**
     * Нужно ли вернуть настройку в выключенное состояние.
     *
     * @param requestedEnabled что просил пользователь
     * @param schedulingFailed планировщик отказал (исключение при постановке работы)
     */
    fun shouldRevert(requestedEnabled: Boolean, schedulingFailed: Boolean): Boolean =
        requestedEnabled && schedulingFailed
}
